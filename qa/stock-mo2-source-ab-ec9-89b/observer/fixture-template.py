def require(condition: bool, message: str) -> None:
    if not condition:
        raise ValueError(message)


def own_path(path: Path, *, directory: bool) -> Path:
    info = path.lstat()
    require(not getattr(info, "st_file_attributes", 0) & stat.FILE_ATTRIBUTE_REPARSE_POINT
            and (stat.S_ISDIR if directory else stat.S_ISREG)(info.st_mode),
            "Non-regular, linked, or reparse fixture path refused")
    return path


def package_digest(root: Path, *, runtime_helper: bool = False) -> str:
    own_path(root, directory=True)
    paths = []
    for base, directories, files in os.walk(root, followlinks=False):
        for name in directories:
            own_path(Path(base) / name, directory=True)
        directories[:] = [name for name in directories if name not in {"__pycache__", "data"}]
        for name in files:
            p = own_path(Path(base) / name, directory=False)
            if runtime_helper and p.relative_to(root).as_posix() == "bin/modhunter-qt-bridge.dll":
                continue
            if p.suffix != ".pyc":
                paths.append(p)
    digest = hashlib.sha256()
    for path in sorted(paths, key=lambda p: p.relative_to(root).as_posix()):
        rel = path.relative_to(root).as_posix()
        require(0 < path.stat().st_size <= 32 * 1024 * 1024, "Invalid production file size")
        digest.update(rel.encode("utf-8") + b"\0" + hashlib.sha256(path.read_bytes()).digest())
    return digest.hexdigest()


def plan(rows: int) -> dict[str, bool]:
    require(type(rows) is int and rows in SIZES, "Expected the declared 2,000 or 11,207 rows")
    return {f"Perf Fixture {i + 1:05d}": i % 4 != 3 for i in range(rows)}


def fixture_digest(expected: dict[str, bool]) -> str:
    return hashlib.sha256(json.dumps(expected, separators=(",", ":"), sort_keys=True).encode()).hexdigest()


def write_new(path: Path, contents: str) -> None:
    with path.open("x", encoding="utf-8", newline="") as handle:
        handle.write(contents)


def seed(root: Path, rows: int) -> None:
    expected = plan(rows)
    own_path(root, directory=True)
    marker = own_path(root / "modhunter-smoke-fixture.json", directory=False)
    require(marker.stat().st_size <= 4096, "Invalid stock fixture marker")
    stock = json.loads(marker.read_text(encoding="utf-8"))
    require(stock.get("purpose") == "isolated native MO2 CI fixture" and bool(stock.get("runId")),
            "Not the disposable stock smoke instance")
    mods = own_path(root / "mods", directory=True)
    profiles = own_path(root / "profiles", directory=True)
    profile = own_path(profiles / PROFILE, directory=True)
    require(not any(mods.iterdir()) and not any(profile.iterdir())
            and not (root / "modhunter-stock-scale.json").exists(),
            "Refuse existing profile or mod contents")
    for i, name in enumerate(expected):
        directory = mods / name
        directory.mkdir()
        source = "" if i % 4 else f"url=https://github.com/fixture/perf-{i+1:05d}\r\n"
        write_new(directory / "meta.ini",
                  f"[General]\r\ngameName={GAME}\r\nmodid=0\r\nversion=1.0.0\r\nrepository=Local\r\n"
                  f"notes=Disposable synthetic directory {i+1:05d}\r\n{source}")
        write_new(directory / f"perf-fixture-{i+1:05d}.txt", "Inert benchmark file. No executable content.\r\n")
    # MO2 profiles store higher-priority rows first on disk. Activation is
    # independently witnessed in the returned native catalog.
    lines = [(("+" if active else "-") + name) for name, active in reversed(expected.items())]
    write_new(profile / "modlist.txt", "# This file was automatically generated by Mod Organizer.\r\n"
              + "\r\n".join(lines) + "\r\n")
    write_new(root / "modhunter-stock-scale.json", json.dumps({
        "test": TEST, "source": VERSION, "rows": rows, "profile": PROFILE,
        "fixtureHash": fixture_digest(expected), "runId": stock["runId"],
    }, sort_keys=True))


def verify_catalog(catalog: dict[str, Any], native_order: list[str], rows: int) -> dict[str, Any]:
    expected = plan(rows)
    require(catalog.get("profileName") == PROFILE and catalog.get("game") == GAME
            and bool(catalog.get("profileId")), "Wrong stock catalog identity")
    items = catalog["items"]
    projected = [item["mo2InternalName"] for item in items]
    require(len(projected) == len(set(projected)) and projected == native_order
            and catalog.get("build", {}).get("count") == len(projected),
            "Stock projection is not the complete ordered native mod inventory")
    active = {item["mo2InternalName"]: item["enabled"] for item in items}
    require({name for name in projected if name.startswith("Perf Fixture ")} == expected.keys()
            and all(active.get(name) is enabled for name, enabled in expected.items()),
            "Stock fixture rows missing, duplicated, added or activated incorrectly")
    order_bytes = json.dumps(projected, separators=(",", ":")).encode()
    return {"requestedRows": rows, "fixtureRows": len(expected), "allNativeRows": len(projected),
            "activeFixtureRows": sum(expected.values()), "orderHash": hashlib.sha256(order_bytes).hexdigest(),
            "fixtureHash": fixture_digest(expected)}


def timing(init: int, ui: int, first_attempt: int, published: int, points: list[int]) -> dict[str, Any]:
    require(init <= ui <= first_attempt <= published
            and 1 <= len(points) <= MAX_TICKS and points[-1] >= published
            and all(a < b for a, b in zip(points, points[1:])),
            "No genuine Qt timer interval through publication or inconsistent phases")
    # Count that final real Qt heartbeat after the ready marker. MO2 can begin
    # a fully synchronous case before even its first timer tick.
    window = [ui, *(t for t in points if ui < t <= points[-1])]
    require(len(window) >= 2, "Missing Qt tick after UI readiness")
    gaps = [(b-a)/1e6 for a, b in zip(window, window[1:])]
    true_gaps = [(b-a)/1e6 for a, b in zip(window[1:], window[2:])]
    return {"pluginInitToPublicationMs": (published-init)/1e6, "uiReadyToPublicationMs": (published-ui)/1e6,
            "firstAttemptToPublicationMs": (published-first_attempt)/1e6,
            "publicationToNextQtTickMs": (points[-1]-published)/1e6,
            "firstUiReadyBoundaryToTickMs": gaps[0], "maxCoveredGapMs": max(gaps),
            "uiQtTickCount": len(window)-1, "intervalMs": INTERVAL_MS,
            "timerInterTickP95Ms": sorted(true_gaps)[math.ceil(len(true_gaps)*0.95)-1] if true_gaps else None,
            "qtTickOffsetsFromUiMs": [(t-ui)/1e6 for t in window[1:]]}
